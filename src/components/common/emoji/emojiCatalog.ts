export type EmojiCategory =
  | 'Smileys & Emotion'
  | 'People & Body'
  | 'Animals & Nature'
  | 'Food & Drink'
  | 'Travel & Places'
  | 'Activities'
  | 'Objects'
  | 'Symbols'
  | 'Flags';

export interface EmojiDefinition {
  char: string;
  name: string;
  hex: string;
  category: EmojiCategory;
  keywords: string[];
}

/**
 * Converts a Unicode emoji string into a CDN-compatible hyphenated hex code point string.
 * Strips variation selector-16 (fe0f) for compatibility with Twemoji, Apple, and Google CDNs.
 */
export function emojiToHex(emoji: string): string {
  const codePoints: string[] = [];
  for (const codePoint of emoji) {
    const cp = codePoint.codePointAt(0);
    if (cp && cp !== 0xfe0f && cp !== 0xfe0e) {
      codePoints.push(cp.toString(16).toLowerCase());
    }
  }
  return codePoints.join('-');
}

/**
 * Converts a Unicode emoji string into a raw hyphenated hex code point string,
 * preserving variation selector-16 (fe0f) for compatibility with Apple and WhatsApp CDNs.
 */
export function emojiToRawHex(emoji: string): string {
  const codePoints: string[] = [];
  for (const codePoint of emoji) {
    const cp = codePoint.codePointAt(0);
    if (cp) {
      codePoints.push(cp.toString(16).toLowerCase());
    }
  }
  return codePoints.join('-');
}

