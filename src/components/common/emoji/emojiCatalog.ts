// Helper to construct definitions quickly
function e(char: string, name: string, category: EmojiCategory, extraKeywords: string[] = []): EmojiDefinition {
  const hex = emojiToHex(char);
  const words = name.toLowerCase().split(/\s+/);
  return {
    char,
    name,
    hex,
    category,
    keywords: Array.from(new Set([...words, ...extraKeywords.map((k) => k.toLowerCase())])),
  };
}

